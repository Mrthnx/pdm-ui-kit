#!/usr/bin/env node
/**
 * Post-build script:
 * 1. Adds clean sub-path aliases (./button → ./src/button FESM)
 * 2. Adds typesVersions for TypeScript moduleResolution:node compatibility
 *
 * ng-packagr generates ./src/button → fesm2020/pdm-ui-kit-src-button.mjs.
 * This script adds the clean aliases without the 'src/' prefix AND
 * typesVersions so Angular 14 consumers (moduleResolution:node) can resolve types.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.resolve(__dirname, "..", "dist", "pdm-ui-kit");

// All secondary entry points (without 'src/' prefix)
const aliases = [
	"accordion",
	"alert",
	"aspect-ratio",
	"avatar",
	"badge",
	"breadcrumb",
	"button",
	"calendar",
	"card",
	"carousel",
	"chart",
	"checkbox",
	"collapsible",
	"combobox",
	"command",
	"context-menu",
	"data-table",
	"dialog",
	"drawer",
	"dropdown-menu",
	"empty",
	"field",
	"hover-card",
	"icon",
	"input",
	"item",
	"kbd",
	"label",
	"menubar",
	"native-select",
	"navigation-menu",
	"pagination",
	"popover",
	"progress",
	"radio-group",
	"scroll-area",
	"select",
	"separator",
	"sidebar",
	"skeleton",
	"slider",
	"sonner",
	"spinner",
	"switch",
	"tabs",
	"toggle",
	"tooltip",
	"overlay",
	"utils",
	"virtual-table",
];

const pkgPath = path.join(DIST, "package.json");
const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8"));
const exportsMap = pkg.exports || {};

// ── 1. Clean alias entries in exports ──────────────────────────────────────
let addedCount = 0;
for (const name of aliases) {
	const srcPath = `./src/${name}`;
	const cleanPath = `./${name}`;
	if (exportsMap[srcPath]) {
		exportsMap[cleanPath] = { ...exportsMap[srcPath] };
		addedCount++;
	}
}
pkg.exports = exportsMap;

// ── 2. typesVersions (for moduleResolution:node — Angular 14 default) ──────
// TypeScript with moduleResolution:node ignores the exports.types field.
// typesVersions is the supported workaround for sub-path type resolution.
const typesVersions = { "*": {} };
for (const name of aliases) {
	const dtsPath = `./src/${name}/index.d.ts`;
	// Only add if the declaration file actually exists
	if (fs.existsSync(path.join(DIST, `src/${name}/index.d.ts`))) {
		typesVersions["*"][name] = [dtsPath];
	}
}
pkg.typesVersions = typesVersions;
typesVersions["*"]["tailwind-preset"] = ["./tailwind-preset.d.ts"];

// ── 3. Standalone Tailwind preset (CJS + ESM) ──────────────────────────────
// The kit ships as ESM only, so `require('pdm-ui-kit')` fails in CommonJS
// tailwind configs. The z-index scale is therefore also emitted as a plain
// dependency-free preset file that any config can load.
const zIndexSource = fs.readFileSync(
	path.resolve(__dirname, "..", "src", "utils", "z-index.ts"),
	"utf-8",
);

const zIndexValueMatch = zIndexSource.match(
	/export const Z_INDEX_VALUE[^=]*=\s*({[\s\S]*?});/,
);

if (!zIndexValueMatch) {
	throw new Error(
		"postbuild-exports: could not read Z_INDEX_VALUE from src/utils/z-index.ts",
	);
}

/** @type {Record<string, number>} */
const zIndexValues = JSON.parse(
	zIndexValueMatch[1]
		.replace(/([A-Za-z][A-Za-z0-9]*)\s*:/g, '"$1":')
		.replace(/,(\s*})/g, "$1"),
);

const preset = {
	theme: {
		extend: {
			zIndex: {
				base: zIndexValues.base,
				dropdown: zIndexValues.dropdown,
				sticky: zIndexValues.sticky,
				"drawer-backdrop": zIndexValues.drawerBackdrop,
				drawer: zIndexValues.drawer,
				"modal-backdrop": zIndexValues.modalBackdrop,
				modal: zIndexValues.modal,
				popover: zIndexValues.popover,
				"loading-blocker": zIndexValues.loadingBlocker,
				toast: zIndexValues.toast,
				"loading-overlay": zIndexValues.loadingOverlay,
			},
		},
	},
};

const presetJson = JSON.stringify(preset, null, 2);

fs.writeFileSync(
	path.join(DIST, "tailwind-preset.cjs"),
	`// Generated by scripts/postbuild-exports.mjs — do not edit.\n` +
		`// Tailwind preset with the pdm-ui-kit z-index scale.\n` +
		`const PDM_TAILWIND_PRESET = ${presetJson};\n\n` +
		`module.exports = { PDM_TAILWIND_PRESET };\n` +
		`module.exports.default = PDM_TAILWIND_PRESET;\n`,
);

fs.writeFileSync(
	path.join(DIST, "tailwind-preset.mjs"),
	`// Generated by scripts/postbuild-exports.mjs — do not edit.\n` +
		`// Tailwind preset with the pdm-ui-kit z-index scale.\n` +
		`export const PDM_TAILWIND_PRESET = ${presetJson};\n\n` +
		`export default PDM_TAILWIND_PRESET;\n`,
);

fs.writeFileSync(
	path.join(DIST, "tailwind-preset.d.ts"),
	`// Generated by scripts/postbuild-exports.mjs — do not edit.\n` +
		`export interface PdmTailwindPreset {\n` +
		`\treadonly theme: {\n` +
		`\t\treadonly extend: {\n` +
		`\t\t\treadonly zIndex: { readonly [token: string]: number };\n` +
		`\t\t};\n` +
		`\t};\n` +
		`}\n\n` +
		`export declare const PDM_TAILWIND_PRESET: PdmTailwindPreset;\n\n` +
		`export default PDM_TAILWIND_PRESET;\n`,
);

exportsMap["./tailwind-preset"] = {
	types: "./tailwind-preset.d.ts",
	require: "./tailwind-preset.cjs",
	import: "./tailwind-preset.mjs",
	default: "./tailwind-preset.mjs",
};

pkg.exports = exportsMap;

fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");

console.log(`Added ${addedCount} clean sub-path aliases`);
console.log(
	`Added typesVersions for ${Object.keys(typesVersions["*"]).length} sub-paths`,
);
console.log("Generated tailwind-preset.cjs / tailwind-preset.mjs");
console.log(`Total exports entries: ${Object.keys(exportsMap).length}`);
